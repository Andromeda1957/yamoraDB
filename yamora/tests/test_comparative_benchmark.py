class DatasetTests(unittest.TestCase):
    def test_splitmix64_matches_the_published_reference_sequence(self):
        generator = dataset.SplitMix64(0)
        self.assertEqual(
            [generator.next_u64() for _ in range(3)],
            [0xE220A8397B1DCDAF, 0x6E789E6AA1B965F4, 0x06C45D188009454F],
        )

    def test_bounded_draws_stay_in_range_and_reject_bad_arguments(self):
        generator = dataset.SplitMix64(99)
        self.assertTrue(all(0 <= generator.below(7) < 7 for _ in range(500)))
        self.assertEqual(generator.below(1), 0)
        with self.assertRaises(ValueError):
            generator.below(0)
        with self.assertRaises(ValueError):
            dataset.derived(-1, 1, 0)

    def test_dataset_digest_is_pinned_for_a_seed(self):
        # Any change to a generated byte changes every comparison made with
        # the dataset, so bump DATASET_VERSION and these digests together.
        self.assertEqual(
            dataset.build_expectations(dataset.DEFAULT_SEED, 100).sha256,
            "83c105ef6ccf9eb0ccf66965b29b1c5051d7c9e1fdeaf6ba38c43fd886c4b04f",
        )
        self.assertEqual(
            dataset.build_expectations(7, 100).sha256,
            "9333477a8fb328d71a37b7ee84edadfe8c5f598234e0155762282c631b24185a",
        )

    def test_documents_are_deterministic_and_independent_of_order(self):
        forward = [dataset.document_fields(5, index) for index in range(50)]
        backward = [dataset.document_fields(5, index) for index in reversed(range(50))]
        self.assertEqual(forward, list(reversed(backward)))
        self.assertNotEqual(forward, [dataset.document_fields(6, index) for index in range(50)])
        batches = list(dataset.batches(5, 50, 7))
        self.assertEqual([item.fields for batch in batches for item in batch], forward)
        self.assertEqual([len(batch) for batch in batches], [7] * 7 + [1])
        with self.assertRaises(ValueError):
            next(dataset.batches(5, 0, 7))

    def test_documents_have_the_documented_shape(self):
        documented = [key for key in dataset.SHAPE if key not in ("id", "yaml_comment")]
        self.assertEqual(list(dataset.document_fields(dataset.DEFAULT_SEED, 0)), documented)
        low, high = dataset.DESCRIPTION_WORDS
        for index in range(300):
            fields = dataset.document_fields(dataset.DEFAULT_SEED, index)
            self.assertRegex(fields["category"], r"^c[0-3][0-9]$")
            self.assertTrue(0 <= fields["price"] < dataset.PRICE_LIMIT)
            self.assertTrue(1.0 <= fields["rating"] <= 5.0)
            self.assertTrue(0 <= fields["stock"] < 1000)
            self.assertEqual(len(set(fields["tags"])), dataset.TAGS_PER_DOCUMENT)
            words = fields["description"].split()
            self.assertTrue(low <= len(words) <= high)
            self.assertTrue(set(words) <= set(dataset.VOCABULARY))
        self.assertEqual(len(set(dataset.VOCABULARY)), dataset.VOCABULARY_SIZE)
        self.assertEqual(dataset.document_id(42), "doc-00000042")
        with self.assertRaises(ValueError):
            dataset.document_id(100_000_000)

    @unittest.skipUnless(yaml is not None, "PyYAML is not installed; YAML round trip unchecked")
    def test_yaml_and_json_encodings_carry_the_same_values(self):
        for index in range(200):
            fields = dataset.document_fields(3, index)
            text = dataset.to_yaml(dataset.document_id(index), fields)
            self.assertTrue(
                text.startswith(f"# Yamora comparative benchmark document doc-{index:08d}\n")
            )
            self.assertEqual(yaml.safe_load(text), fields)
            self.assertEqual(json.loads(dataset.to_json(fields)), fields)

    def test_operation_streams_are_reproducible_and_warmups_differ(self):
        for workload in ("point_read", "query_eq", "query_range", "text", "update", "mixed"):
            with self.subTest(workload=workload):
                first = dataset.operations(11, workload, 200, 1000)
                self.assertEqual(first, dataset.operations(11, workload, 200, 1000))
                self.assertNotEqual(first, dataset.operations(11, workload, 200, 1000, warmup=True))
                self.assertNotEqual(first, dataset.operations(12, workload, 200, 1000))
        reads = dataset.operations(11, "point_read", 500, 1000)
        self.assertTrue(all(0 <= int(item[1].removeprefix("doc-")) < 1000 for item in reads))
        ranges = dataset.operations(11, "query_range", 500, 1000)
        self.assertTrue(all(high - low == dataset.RANGE_WIDTH for _, low, high in ranges))
        self.assertTrue(all(high <= dataset.PRICE_LIMIT for _, _, high in ranges))
        mixed = dataset.operations(11, "mixed", 5000, 1000)
        share = sum(1 for item in mixed if item[0] == "get") / len(mixed)
        self.assertAlmostEqual(share, dataset.MIXED_READ_PERCENT / 100, delta=0.03)
        self.assertEqual(dataset.operations(11, "aggregate", 2, 1000), [("aggregate",)] * 2)
        with self.assertRaises(ValueError):
            dataset.operations(11, "document", 1, 1000)

    def test_partition_is_round_robin_and_complete(self):
        items = list(range(11))
        shares = dataset.partition(items, 3)
        self.assertEqual(shares, [[0, 3, 6, 9], [1, 4, 7, 10], [2, 5, 8]])
        self.assertEqual(sorted(value for share in shares for value in share), items)
        with self.assertRaises(ValueError):
            dataset.partition(items, 0)

    def test_expectations_match_a_brute_force_scan(self):
        expectations = dataset.build_expectations(21, 400)
        documents = [dataset.document_fields(21, index) for index in range(400)]
        for low, high in ((0, 500), (12_345, 12_845), (99_500, 100_000)):
            brute = sum(1 for item in documents if low <= item["price"] < high)
            self.assertEqual(expectations.range_count(low, high), brute)
        self.assertEqual(sum(expectations.category_counts.values()), 400)
        self.assertEqual(expectations.stock_sum, sum(item["stock"] for item in documents))
        word = documents[0]["description"].split()[0]
        holders = sum(1 for item in documents if word in item["description"].split())
        self.assertEqual(expectations.term_documents[word], holders)
        self.assertEqual(
            expectations.expected_rows(("text", word)), min(holders, dataset.QUERY_LIMIT)
        )
        rows = expectations.aggregate_rows()
        self.assertEqual([row["_id"] for row in rows], sorted(row["_id"] for row in rows))
        self.assertEqual(sum(row["count"] for row in rows), 400)
        self.assertEqual(dataset.deleted_indexes(7), [1, 3, 5])
        self.assertEqual(expectations.describe()["documents"], 400)


class StatisticsTests(unittest.TestCase):
    def test_percentiles_use_linear_interpolation(self):
        values = list(range(1, 11))
        self.assertEqual(stats.percentile(values, 0), 1.0)
        self.assertEqual(stats.percentile(values, 50), 5.5)
        self.assertAlmostEqual(stats.percentile(values, 95), 9.55)
        self.assertAlmostEqual(stats.percentile(values, 99), 9.91)
        self.assertEqual(stats.percentile(values, 100), 10.0)
        self.assertEqual(stats.percentile([4], 99), 4.0)
        with self.assertRaises(ValueError):
            stats.percentile([], 50)
        with self.assertRaises(ValueError):
            stats.percentile(values, 101)

    def test_median(self):
        self.assertEqual(stats.median([3, 1, 2]), 2.0)
        self.assertEqual(stats.median([4, 1, 3, 2]), 2.5)
        self.assertEqual(stats.median_bytes([10, 13]), 12)  # round(11.5) is 12
        with self.assertRaises(ValueError):
            stats.median([])

    def test_summarize_reports_throughput_and_latency(self):
        latencies = [1_000_000 * value for value in range(1, 101)]  # 1..100 ms
        summary = stats.summarize(latencies, wall_ns=2_000_000_000, concurrency=2)
        self.assertEqual(summary["operations"], 100)
        self.assertEqual(summary["items"], 100)
        self.assertEqual(summary["concurrency"], 2)
        self.assertEqual(summary["throughput_ops_s"], 50.0)
        self.assertEqual(summary["latency_ms"]["p50"], 50.5)
        self.assertAlmostEqual(summary["latency_ms"]["p99"], 99.01)
        self.assertEqual(summary["latency_ms"]["max"], 100.0)
        batch = stats.summarize([5_000_000] * 4, wall_ns=20_000_000, items=400)
        self.assertEqual(batch["throughput_items_s"], 20_000.0)
        self.assertEqual(batch["throughput_ops_s"], 200.0)
        for latencies, wall in (([], 1), ([1], 0), ([-1], 1)):
            with self.subTest(latencies=latencies, wall=wall), self.assertRaises(ValueError):
                stats.summarize(latencies, wall_ns=wall)

    def test_combine_takes_medians_and_keeps_the_spread(self):
        runs = [
            stats.summarize([value * 1_000_000] * 10, wall_ns=wall)
            for value, wall in ((1, 1_000_000_000), (3, 2_000_000_000), (2, 4_000_000_000))
        ]
        combined = stats.combine(runs)
        self.assertEqual(combined["repetitions"], 3)
        self.assertEqual(combined["wall_seconds"], 2.0)
        self.assertEqual(combined["throughput_ops_s"], 5.0)
        self.assertEqual(combined["throughput_ops_s_range"], [2.5, 10.0])
        self.assertEqual(combined["latency_ms"]["p50"], 2.0)
        schema.validate_phase(combined, "combined", combined=True)
        mismatched = copy.deepcopy(runs)
        mismatched[1]["operations"] = 9
        with self.assertRaises(ValueError):
            stats.combine(mismatched)
        with self.assertRaises(ValueError):
            stats.combine([])

    def test_engine_order_rotates_each_repetition(self):
        engines = ["yamora", "mongodb", "postgresql"]
        self.assertEqual(_engine_order(engines, 1), engines)
        self.assertEqual(_engine_order(engines, 2), ["mongodb", "postgresql", "yamora"])
        self.assertEqual(_engine_order(engines, 4), engines)

    def test_profiles_match_the_documented_scales(self):
        smoke = config.PROFILES["smoke"]
        self.assertTrue(1_000 <= smoke.documents <= 5_000)
        self.assertEqual(smoke.repetitions, 1)
        self.assertGreaterEqual(config.PROFILES["full"].repetitions, 3)
        workloads = set(config.READ_WORKLOADS) | set(config.WRITE_WORKLOADS) | {"aggregate"}
        for profile in config.PROFILES.values():
            self.assertEqual(set(profile.operations), workloads)
            self.assertGreaterEqual(profile.warmup(profile.operations["point_read"]), 1)
        self.assertTrue(schema.smoke_label_ok(config.SMOKE_LABEL))


def _phase(milliseconds: float = 1.0, operations: int = 10, items: int | None = None) -> dict:
    return stats.summarize(
        [int(milliseconds * 1_000_000)] * operations,
        wall_ns=int(milliseconds * 1_000_000 * operations),
        items=items,
    )


def _run(engine: str) -> dict:
    usage = {"allocated_bytes": 4096, "apparent_bytes": 1000, "files": 1}
    return {
        "engine": engine,
        "repetition": 1,
        "status": "ok",
        "phases": {"ingest": _phase(items=1000), "point_read@c1": _phase(), "aggregate": _phase()},
        "disk": {"after_ingest": usage, "after_deletes": usage},
        "checks": {"count_after_ingest": 1000},
        "memory": {"peak_rss_bytes": 1 << 20, "peak_pss_bytes": 1 << 19, "samples": 3},
        "teardown": {"container_removed": True, "data_removed": True},
    }


def _result(profile: str = "full", label: str | None = None) -> dict:
    """A minimal valid result document, summarized by the real summary code."""
    engines = ["yamora", "mongodb", "postgresql"]
    runs = [_run(engine) for engine in engines]
    return {
        "schema": config.SCHEMA,
        "label": label,
        "profile": profile,
        "created_at": "2026-10-31T00:00:00+00:00",
        "duration_seconds": 1.0,
        "command": ["python", "-m", "yamora.benchmarks.compare", "run"],
        "source": {"commit": "0" * 40, "yamora_tree_dirty": False},
        "machine": {
            "kernel": "6.0",
            "logical_cpus": 8,
            "filesystem": {"type": "ext4", "mount_options": "rw", "superblock_options": "rw"},
            "os": "Test OS",
            "cpu_model": "Test CPU",
            "memory_total_bytes": 1 << 34,
            "load_average_at_start": [0.1, 0.1, 0.1],
            "load_average_at_end": [0.2, 0.1, 0.1],
        },
        "podman": {"version": "6.1.4"},
        "dataset": dataset.build_expectations(1, 1000).describe(),
        "settings": {
            **config.PROFILES["smoke"].describe(),
            "documents": 1000,
            "limits": {"cpus": "2", "memory": "1g"},
        },
        "engines": {
            engine: {
                "version": "1",
                "durability": "durable",
                "client": "client",
                "server_command": ["server"],
                "cache": "256 MiB",
            }
            for engine in engines
        },
        "runs": runs,
        "summary": _summarize(runs, engines),
        "excluded_workloads": [],
        "caveats": ["Only the measured workload."],
        "teardown": {
            "containers_remaining": [],
            "networks_remaining": [],
            "work_directory_removed": True,
        },
    }


def _phase_of(value: dict, engine: int, phase: str) -> dict:
    return value["runs"][engine]["phases"][phase]


class SchemaTests(unittest.TestCase):
    def test_a_complete_result_validates(self):
        schema.validate_result(_result())
        schema.validate_result(_result("smoke", FIXTURE_LABEL))

    def test_incomplete_or_inconsistent_results_are_rejected(self):
        cases = {
            "missing caveats": lambda value: value.pop("caveats"),
            "empty caveats": lambda value: value.update(caveats=[]),
            "wrong schema": lambda value: value.update(schema="other/1"),
            "unordered percentiles": lambda value: _phase_of(value, 0, "point_read@c1")[
                "latency_ms"
            ].update(p95=0.1),
            "unknown phase": lambda value: value["runs"][0]["phases"].update(sleep=_phase()),
            "zero wall time": lambda value: _phase_of(value, 0, "aggregate").update(wall_seconds=0),
            "boolean count": lambda value: _phase_of(value, 0, "aggregate").update(operations=True),
            "size mismatch": lambda value: value["settings"].update(documents=5),
            "bad digest": lambda value: value["dataset"].update(sha256="abc"),
            "failed without error": lambda value: value["runs"][0].update(status="failed"),
            "ok without disk": lambda value: value["runs"][0].update(disk={}),
            "ok without memory": lambda value: value["runs"][0].pop("memory"),
            "unknown engine": lambda value: value["runs"][0].update(engine="sqlite"),
            "no runs": lambda value: value.update(runs=[]),
            "teardown not boolean": lambda value: value["teardown"].update(
                work_directory_removed="yes"
            ),
            "median outside spread": lambda value: value["summary"]["yamora"]["phases"][
                "ingest"
            ].update(throughput_ops_s_range=[0.0, 0.5]),
        }
        for name, change in cases.items():
            value = _result()
            change(value)
            with self.subTest(name), self.assertRaises(schema.SchemaError):
                schema.validate_result(value)

    def test_a_smoke_result_must_say_it_is_not_a_benchmark(self):
        for label in (None, "", "smoke", "quick check, not a benchmark result"):
            with self.subTest(label=label), self.assertRaises(schema.SchemaError):
                schema.validate_result(_result("smoke", label))

    def test_committed_example_is_a_labelled_clean_smoke_run(self):
        result = json.loads(FIXTURE.read_text(encoding="utf-8"))
        schema.validate_result(result)
        self.assertEqual(result["profile"], "smoke")
        self.assertEqual(result["label"], FIXTURE_LABEL)
        self.assertEqual(sorted(result["engines"]), ["mongodb", "postgresql", "yamora"])
        self.assertTrue(all(run["status"] == "ok" for run in result["runs"]))
        self.assertTrue(all(all(run["teardown"].values()) for run in result["runs"]))
        self.assertEqual(
            result["teardown"],
            {"containers_remaining": [], "networks_remaining": [], "work_directory_removed": True},
        )
        self.assertFalse(result["source"]["yamora_tree_dirty"])
        text = report.render(result, source_name=FIXTURE.name)
        self.assertIn("its figures are not performance results", text)


