#!/usr/bin/env python3
"""Generate pinned Unicode 17.0 word categories and default full case folding.

Inputs: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt and
https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt, downloaded separately.
Normal daemon builds use the checked-in header and need neither Python nor data
downloads. Derived data is covered by ../UNICODE-LICENSE.txt.
"""

import argparse
from pathlib import Path


def generate(unicode_data: Path, case_folding: Path) -> str:
    intervals: list[tuple[int, int]] = []
    pending: tuple[int, str] | None = None
    for line in unicode_data.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        if len(fields) != 15:
            raise ValueError("invalid UnicodeData record")
        code = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            pending = (code, fields[2])
            continue
        if fields[1].endswith(", Last>"):
            if pending is None or pending[1] != fields[2]:
                raise ValueError("invalid UnicodeData range")
            first, category = pending
            pending = None
        else:
            first, category = code, fields[2]
        if category[0] in "LMN":
            if intervals and intervals[-1][1] + 1 == first:
                intervals[-1] = (intervals[-1][0], code)
            else:
                intervals.append((first, code))
    if pending:
        raise ValueError("unterminated UnicodeData range")
    folding = case_folding.read_text(encoding="utf-8")
    if not folding.startswith("# CaseFolding-17.0.0.txt"):
        raise ValueError("expected Unicode 17.0.0 case folding")
    mappings = []
    for line in folding.splitlines():
        record = line.partition("#")[0].strip()
        if not record:
            continue
        code_hex, status, target, _ = [field.strip() for field in record.split(";")]
        if status not in {"C", "F"}:
            continue
        output = [int(item, 16) for item in target.split()]
        if not 1 <= len(output) <= 3:
            raise ValueError("unsupported case folding expansion")
        mappings.append((int(code_hex, 16), output))
    lines = [
        "/* Generated by tools/generate_text_tables.py from Unicode 17.0.0.",
        " * Unicode data copyright: Unicode, Inc.; see UNICODE-LICENSE.txt.",
        " * This is runtime data; no system locale or Unicode library is used. */",
        "#ifndef YAMORA_TEXT_UNICODE_H",
        "#define YAMORA_TEXT_UNICODE_H",
        "#include <stdint.h>",
        "typedef struct { uint32_t first, last; } YDTextRange;",
        "typedef struct { uint32_t code, count, mapped[3]; } YDTextFold;",
        "static const YDTextRange yd_text_word_ranges[] = {",
    ]
    lines.extend(f"    {{0x{first:x}, 0x{last:x}}}," for first, last in intervals)
    lines.extend(["};", "static const YDTextFold yd_text_folding[] = {"])
    for code, output in sorted(mappings):
        padded = output + [0] * (3 - len(output))
        values = ", ".join(f"0x{value:x}" for value in padded)
        lines.append(f"    {{0x{code:x}, {len(output)}, {{{values}}}}},")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unicode-data", type=Path, required=True)
    parser.add_argument("--case-folding", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.unicode_data, args.case_folding), encoding="utf-8")


if __name__ == "__main__":
    main()
